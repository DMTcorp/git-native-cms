import { writeFile } from "node:fs/promises";
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
import { editorPreviewSchema, previewEditorSchema } from "../dist/preview-schemas.js";

const ajv = new Ajv({
  strict: true,
  formats: { "date-time": true },
  code: { source: true, esm: true },
});
ajv.addSchema(editorPreviewSchema);
ajv.addSchema(previewEditorSchema);

const validators = {
  validateEditorPreview: editorPreviewSchema.$id,
  validatePreviewEditor: previewEditorSchema.$id,
};
for (const schemaId of Object.values(validators)) {
  if (ajv.getSchema(schemaId) === undefined) {
    throw new Error(`Ajv did not compile ${schemaId}.`);
  }
}

const generated = standaloneCode(ajv, validators).replace(
  'const func2 = require("ajv/dist/runtime/ucs2length").default;',
  'import func2Module from "ajv/dist/runtime/ucs2length.js";const func2 = typeof func2Module === "function" ? func2Module : func2Module.default;',
);
if (generated.includes("require(") || /\b(?:eval|Function)\s*\(/u.test(generated)) {
  throw new Error("The browser validator contains code forbidden by the production CSP.");
}

const output = `/* eslint-disable */
// @ts-nocheck
// Generated by scripts/generate-preview-validators.mjs. Do not edit by hand.

${generated}
`;
await writeFile(new URL("../src/generated/preview-validators.ts", import.meta.url), output);
